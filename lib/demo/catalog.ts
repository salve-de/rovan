/** 既存の見本データと同じ、実在しにくい架空の屋号 */
const FICTIONAL_PREFIXES = ["月澄", "花継", "星紡ぎ", "結ノ葉", "灯和", "蒼路", "紬野", "和つばさ", "晴結", "栞月", "結樹", "朝凪"];

export function detectIndustry(text: string): DemoIndustry {
  return DEMO_INDUSTRIES.find((industry) => industry.match.test(text)) || GENERIC_INDUSTRY;
}

const CORPORATE = /^(?:株式会社|有限会社|合同会社|合資会社|一般社団法人|医療法人|社会福祉法人)$/u;
const PLACE_TOKEN = /^[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}ー]{1,8}$/u;

/**
 * 「青葉ベーカリー 高崎」→ 名前「青葉ベーカリー」＋地域「高崎」。
 * 最後の語が短い地名らしい語で、業種の語でなければ地域として扱う。
 */
export function splitNameAndRegion(input: string) {
  const cleaned = input.trim().replace(/^@/u, "").replace(/\s+/gu, " ");
  const tokens = cleaned.split(" ").filter(Boolean);
  const last = tokens[tokens.length - 1] || "";
  const canBeRegion = tokens.length >= 2 && PLACE_TOKEN.test(last) && !CORPORATE.test(last) && detectIndustry(last) === GENERIC_INDUSTRY && !CORPORATE.test(tokens[tokens.length - 2] || "");
  const region = canBeRegion ? last : "";
  const name = (canBeRegion ? tokens.slice(0, -1) : tokens).join(" ") || cleaned;
  return { name, region: region || regionFromText(cleaned) };
}

/** 住所の書き方（「群馬県高崎市」「東京都大田区」）から市区町村を取り出す */
export function regionFromText(text: string) {
  const match = text.match(/(?:東京都|北海道|京都府|大阪府|[\p{Script=Han}]{2,3}県)([\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}]{1,6}?[市区町村郡])/u);
  return match ? match[1] : "";
}

export function hash01(value: string) {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return ((hash >>> 0) % 100_000) / 100_000;
}

/** 業種ごとに8社の架空の比較候補をつくる（毎回同じ名前になる） */
export function fictionalCompetitors(industry: DemoIndustry, seed: string) {
  const offset = Math.floor(hash01(`${seed}:competitors`) * FICTIONAL_PREFIXES.length);
  return Array.from({ length: 8 }, (_, index) => {
    const prefix = FICTIONAL_PREFIXES[(offset + index) % FICTIONAL_PREFIXES.length];
    const stem = industry.stems[index % industry.stems.length];
    return `${prefix}${stem}`;
  });
}

export function regionPhrases(region: string) {
  return { de: region ? `${region}で` : "近くで", no: region ? `${region}の` : "近くの" };
}

